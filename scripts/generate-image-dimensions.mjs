// Scans app/ for Cloudinary image URLs, reads each image's real pixel size and
// writes app/lib/imageDimensions.ts. Components use it to give next/image true
// intrinsic width/height instead of `fill` (no attributes) or guessed values.
//
// Run after adding or changing an image URL:  node scripts/generate-image-dimensions.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from 'fs'
import { join } from 'path'
import sharp from 'sharp'

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const appDir = join(root, 'app')
const outFile = join(appDir, 'lib', 'imageDimensions.ts')

const files = []
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) walk(full)
    else if (/\.(ts|tsx)$/.test(name) && full !== outFile) files.push(full)
  }
}
walk(appDir)

const urls = new Set()
for (const file of files) {
  for (const m of readFileSync(file, 'utf8').matchAll(/https:\/\/res\.cloudinary\.com\/[^'"`\s)]+\.(?:jpe?g|png|webp|avif)/g)) {
    urls.add(m[0])
  }
}

const entries = []
for (const url of [...urls].sort()) {
  try {
    const res = await fetch(url)
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    const { width, height } = await sharp(Buffer.from(await res.arrayBuffer())).metadata()
    entries.push([url, width, height])
  } catch (err) {
    console.warn(`skip ${url}: ${err.message}`)
  }
}

const body = entries.map(([u, w, h]) => `  '${u}': [${w}, ${h}],`).join('\n')
writeFileSync(outFile, `// Generated by scripts/generate-image-dimensions.mjs — do not edit by hand.
// Real pixel dimensions [width, height] of each Cloudinary image used in app/.
export const imageDimensions: Record<string, [number, number]> = {
${body}
}
`)
console.log(`wrote ${entries.length} image sizes to app/lib/imageDimensions.ts`)
